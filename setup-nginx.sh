#!/usr/bin/env bash
# Interactive nginx (+ optional HTTPS) setup for CMS on its own three domains:
#   contest  -> ContestWebServer  (default port 8888)
#   admin    -> AdminWebServer    (default port 8889)
#   ranking  -> RankingWebServer  (default port 8890)
#
# Usage:  sudo bash setup-nginx.sh
set -euo pipefail

CONF_NAME="cms"
CONF_AVAIL="/etc/nginx/sites-available/${CONF_NAME}"
CONF_ENABLED="/etc/nginx/sites-enabled/${CONF_NAME}"

# ---------- helpers ----------
if [[ -t 1 ]]; then
  B=$'\e[1m'; G=$'\e[32m'; Y=$'\e[33m'; R=$'\e[31m'; N=$'\e[0m'
else
  B=""; G=""; Y=""; R=""; N=""
fi
info() { echo "${G}==>${N} $*"; }
warn() { echo "${Y}WARNING:${N} $*"; }
die()  { echo "${R}ERROR:${N} $*" >&2; exit 1; }

# Turn "https://Contest.Example.com/" into "contest.example.com"
clean_domain() {
  local d="$1"
  d="${d#http://}"; d="${d#https://}"
  d="${d%%/*}"; d="${d%%:*}"
  d="${d,,}"
  echo "$d"
}

valid_domain() {
  [[ "$1" =~ ^([a-z0-9]([a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,}$ ]]
}

ask_domain() {
  local label="$1" example="$2" ans
  while true; do
    read -r -p "${B}${label}${N} (e.g. ${example}): " ans
    ans="$(clean_domain "$ans")"
    if [[ -z "$ans" ]]; then
      echo "  Please enter a domain."
    elif ! valid_domain "$ans"; then
      echo "  '$ans' doesn't look like a valid domain. Try again."
    else
      echo "$ans"
      return
    fi
  done
}

ask_port() {
  local label="$1" default="$2" ans
  while true; do
    read -r -p "${label} port [${default}]: " ans
    ans="${ans:-$default}"
    if [[ "$ans" =~ ^[0-9]+$ ]] && (( ans >= 1 && ans <= 65535 )); then
      echo "$ans"
      return
    fi
    echo "  Enter a number between 1 and 65535."
  done
}

ask_yes_no() {  # ask_yes_no "question" default(y/n)
  local q="$1" def="$2" ans prompt
  [[ "$def" == "y" ]] && prompt="[Y/n]" || prompt="[y/N]"
  read -r -p "${q} ${prompt} " ans
  ans="${ans:-$def}"
  [[ "${ans,,}" == y* ]]
}

# ---------- root check ----------
if [[ $EUID -ne 0 ]]; then
  echo "This script needs root. Re-running with sudo..."
  exec sudo bash "$0" "$@"
fi

echo
echo "${B}CMS nginx setup${N}"
echo "Enter the three web addresses (with or without https://)."
echo

# ---------- questions ----------
while true; do
  CONTEST_DOMAIN="$(ask_domain "Contest (contestant) site" "contest.example.com")"
  ADMIN_DOMAIN="$(ask_domain   "Admin site"                "admin.example.com")"
  RANKING_DOMAIN="$(ask_domain "Ranking (scoreboard) site" "ranking.example.com")"
  if [[ "$CONTEST_DOMAIN" == "$ADMIN_DOMAIN" || "$CONTEST_DOMAIN" == "$RANKING_DOMAIN" || "$ADMIN_DOMAIN" == "$RANKING_DOMAIN" ]]; then
    warn "The three domains must be different. Let's try again."
    echo
    continue
  fi
  break
done

echo
echo "CMS service ports (press Enter to accept the defaults):"
CWS_PORT="$(ask_port "ContestWebServer" 8888)"
AWS_PORT="$(ask_port "AdminWebServer  " 8889)"
RWS_PORT="$(ask_port "RankingWebServer" 8890)"

echo
echo "${B}Summary${N}"
echo "  Contest : http://${CONTEST_DOMAIN}  -> 127.0.0.1:${CWS_PORT}"
echo "  Admin   : http://${ADMIN_DOMAIN}  -> 127.0.0.1:${AWS_PORT}"
echo "  Ranking : http://${RANKING_DOMAIN}  -> 127.0.0.1:${RWS_PORT}"
echo
ask_yes_no "Continue?" y || die "Cancelled."

# ---------- install packages ----------
info "Installing nginx and certbot (if missing)..."
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq nginx certbot python3-certbot-nginx curl >/dev/null

# ---------- proxy_params ----------
if [[ ! -f /etc/nginx/proxy_params ]]; then
  info "Creating /etc/nginx/proxy_params (it was missing)..."
  cat > /etc/nginx/proxy_params << 'EOF'
proxy_set_header Host $http_host;
proxy_set_header X-Real-IP $remote_addr;
proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
proxy_set_header X-Forwarded-Proto $scheme;
EOF
fi

# ---------- write the config ----------
rm -f /etc/nginx/sites-enabled/default

if [[ -f "$CONF_AVAIL" ]]; then
  BACKUP="${CONF_AVAIL}.bak.$(date +%Y%m%d%H%M%S)"
  cp "$CONF_AVAIL" "$BACKUP"
  info "Existing config backed up to ${BACKUP}"
fi

info "Writing ${CONF_AVAIL}..."
cat > "$CONF_AVAIL" << 'EOF'
# Generated by setup-nginx.sh

# "hash $remote_addr" keeps each contestant on the same ContestWebServer
# (needed if you add more servers below).
upstream cws {
    hash $remote_addr;
    keepalive 500;
    server 127.0.0.1:__CWS_PORT__;
    # Insert other ContestWebServers here.
}

upstream aws {
    keepalive 5;
    server 127.0.0.1:__AWS_PORT__;
}

upstream rws {
    keepalive 500;
    server 127.0.0.1:__RWS_PORT__;
}

# Contestants
server {
    listen 80;
    server_name __CONTEST_DOMAIN__;
    client_max_body_size 50M;

    location / {
        proxy_pass http://cws;
        include proxy_params;
        proxy_http_version 1.1;
        proxy_set_header Connection "";
    }
}

# Admin
server {
    listen 80;
    server_name __ADMIN_DOMAIN__;
    client_max_body_size 100M;

    location / {
        proxy_pass http://aws;
        include proxy_params;
        proxy_http_version 1.1;
        proxy_set_header Connection "";
    }
}

# Public scoreboard
server {
    listen 80;
    server_name __RANKING_DOMAIN__;

    location / {
        proxy_pass http://rws;
        include proxy_params;
        proxy_http_version 1.1;
        proxy_set_header Connection "";
        # Buffering blocks the streaming requests used for live updates.
        proxy_buffering off;
    }
}
EOF

sed -i \
  -e "s/__CONTEST_DOMAIN__/${CONTEST_DOMAIN}/g" \
  -e "s/__ADMIN_DOMAIN__/${ADMIN_DOMAIN}/g" \
  -e "s/__RANKING_DOMAIN__/${RANKING_DOMAIN}/g" \
  -e "s/__CWS_PORT__/${CWS_PORT}/g" \
  -e "s/__AWS_PORT__/${AWS_PORT}/g" \
  -e "s/__RWS_PORT__/${RWS_PORT}/g" \
  "$CONF_AVAIL"

ln -sf "$CONF_AVAIL" "$CONF_ENABLED"

info "Testing nginx configuration..."
if ! nginx -t; then
  die "nginx config test failed. See the message above. (File: ${CONF_AVAIL})"
fi
systemctl enable nginx >/dev/null 2>&1 || true
systemctl reload nginx 2>/dev/null || systemctl restart nginx
info "nginx is configured and reloaded."

# ---------- firewall (only if ufw is active) ----------
if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active"; then
  info "ufw is active; allowing ports 80 and 443..."
  ufw allow 80/tcp >/dev/null
  ufw allow 443/tcp >/dev/null
fi

# ---------- checks ----------
echo
info "Checking your setup..."

PUBLIC_IP="$(curl -s --max-time 5 https://checkip.amazonaws.com | tr -d '[:space:]' || true)"
[[ -n "$PUBLIC_IP" ]] && echo "  This server's public IP: ${PUBLIC_IP}" || warn "Could not detect this server's public IP."

DNS_OK=1
for d in "$CONTEST_DOMAIN" "$ADMIN_DOMAIN" "$RANKING_DOMAIN"; do
  RESOLVED="$(getent ahostsv4 "$d" 2>/dev/null | awk '{print $1; exit}' || true)"
  if [[ -z "$RESOLVED" ]]; then
    warn "${d} does not resolve yet. Create an A record pointing to ${PUBLIC_IP:-this server}."
    DNS_OK=0
  elif [[ -n "$PUBLIC_IP" && "$RESOLVED" != "$PUBLIC_IP" ]]; then
    warn "${d} points to ${RESOLVED}, but this server is ${PUBLIC_IP}."
    DNS_OK=0
  else
    echo "  ${d} -> ${RESOLVED}  OK"
  fi
done

for pair in "ContestWebServer:${CWS_PORT}" "AdminWebServer:${AWS_PORT}" "RankingWebServer:${RWS_PORT}"; do
  name="${pair%%:*}"; port="${pair##*:}"
  if ss -ltn 2>/dev/null | awk '{print $4}' | grep -qE "[:.]${port}\$"; then
    echo "  ${name} is listening on port ${port}  OK"
  else
    warn "Nothing is listening on port ${port} (${name}). You'll see 502 Bad Gateway until CMS is running."
  fi
done

echo
echo "  Reminder: AWS security group must allow inbound TCP 80 and 443 from 0.0.0.0/0."
echo "  Let's Encrypt cannot issue certificates if port 80 is blocked."

# ---------- HTTPS ----------
echo
if ask_yes_no "Set up free HTTPS (Let's Encrypt) now?" y; then
  if (( DNS_OK == 0 )); then
    warn "Some domains don't point to this server yet. Certbot will fail until they do."
    ask_yes_no "Try anyway?" n || { echo "Skipping HTTPS. Re-run this script later."; SKIP_HTTPS=1; }
  fi
  if [[ -z "${SKIP_HTTPS:-}" ]]; then
    read -r -p "Email for certificate notices: " LE_EMAIL
    [[ -n "$LE_EMAIL" ]] || die "An email address is required."
    DOMAINS=(-d "$CONTEST_DOMAIN" -d "$ADMIN_DOMAIN" -d "$RANKING_DOMAIN")

    info "Running a test (dry run) first so a mistake can't use up Let's Encrypt limits..."
    if certbot --nginx --dry-run --non-interactive --agree-tos --no-eff-email -m "$LE_EMAIL" "${DOMAINS[@]}"; then
      info "Dry run passed. Requesting the real certificate..."
      certbot --nginx --non-interactive --agree-tos --no-eff-email --redirect -m "$LE_EMAIL" "${DOMAINS[@]}"
      info "HTTPS is enabled. Automatic renewal test:"
      certbot renew --dry-run >/dev/null 2>&1 && echo "  renewal OK" || warn "renewal test failed; check 'certbot renew --dry-run'"
    else
      warn "The dry run failed, so no real certificate was requested."
      echo "  Most common causes: port 80 closed in the AWS security group, or a domain not pointing to this server."
      echo "  Fix that, then run:  sudo certbot --nginx -d ${CONTEST_DOMAIN} -d ${ADMIN_DOMAIN} -d ${RANKING_DOMAIN}"
    fi
  fi
fi

echo
echo "${B}Done.${N}"
echo "  Contest : https://${CONTEST_DOMAIN}"
echo "  Admin   : https://${ADMIN_DOMAIN}"
echo "  Ranking : https://${RANKING_DOMAIN}"
echo "  (If HTTPS was skipped, use http:// instead.)"
echo "  Config file: ${CONF_AVAIL}"
